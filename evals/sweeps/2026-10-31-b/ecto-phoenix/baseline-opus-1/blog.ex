defmodule MyApp.Repo.Migrations.BackfillPostsPublishedAt do
  use Ecto.Migration

  # Each batch commits on its own, so row locks stay short and writes to posts
  # keep working during the backfill. A failed run can simply be rerun.
  @disable_ddl_transaction true
  @disable_migration_lock true

  @batch_size 1_000
  @throttle_ms 100

  # This stays a normal migration so it runs before the new code starts. From
  # then on NULL means draft, so max_id stops it from publishing any post
  # created after it begins. Posts the old code inserts after that point stay
  # NULL and count as drafts.
  #
  # Raw SQL rather than MyApp.Blog.Post, so later schema changes cannot break it.
  def up do
    %{rows: [[max_id]]} = repo().query!("SELECT coalesce(max(id), 0) FROM posts")

    backfill(0, max_id)
  end

  # Rolling back the previous migration drops the column.
  def down, do: :ok

  defp backfill(last_id, max_id) when last_id >= max_id, do: :ok

  defp backfill(last_id, max_id) do
    next_id = min(last_id + @batch_size, max_id)

    repo().query!(
      """
      UPDATE posts
      SET published_at = inserted_at
      WHERE id > $1 AND id <= $2 AND published_at IS NULL
      """,
      [last_id, next_id]
    )

    Process.sleep(@throttle_ms)
    backfill(next_id, max_id)
  end
end

