defmodule MyApp.Blog do
  @moduledoc """
  The Blog context.
  """

  import Ecto.Query

  alias Ecto.Multi
  alias MyApp.Accounts.User
  alias MyApp.Audit.Log
  alias MyApp.Blog.Post
  alias MyApp.Repo

  @doc """
  Creates a post owned by `user` from form params.
  """
  def create_post(%User{} = user, attrs) do
    %Post{user_id: user.id}
    |> Post.changeset(attrs)
    |> Repo.insert()
  end

  @doc """
  Lists `user`'s posts, newest first, with `:user` preloaded for the author's name.
  """
  def list_user_posts(%User{} = user) do
    # Timestamps have one-second precision, so id breaks ties.
    query =
      from p in Post,
        where: p.user_id == ^user.id,
        order_by: [desc: p.inserted_at, desc: p.id],
        preload: :user

    Repo.all(query)
  end

  @doc """
  Gets a post by id. Raises `Ecto.NoResultsError` if there is none.
  """
  def get_post!(id), do: Repo.get!(Post, id)

  @doc """
  Publishes `post` and writes an audit log row in one transaction.

  Returns `{:ok, post}` or `{:error, :already_published}`. If the audit insert
  raises, the post update is rolled back with it.
  """
  def publish_post(%Post{} = post) do
    now = DateTime.utc_now(:second)

    Multi.new()
    |> Multi.run(:post, fn repo, _changes -> mark_published(repo, post, now) end)
    |> Multi.insert(:audit_log, fn %{post: published} -> publish_log(published) end)
    |> Repo.transaction()
    |> case do
      {:ok, %{post: published}} -> {:ok, published}
      {:error, _step, reason, _changes} -> {:error, reason}
    end
  end

  # The is_nil filter stops a double click or a stale struct from moving the
  # date and writing a second audit row. update_all skips autogenerated
  # fields, so updated_at is set here.
  defp mark_published(repo, %Post{id: id}, now) do
    query = from p in Post, where: p.id == ^id and is_nil(p.published_at), select: p

    case repo.update_all(query, set: [published_at: now, updated_at: now]) do
      {1, [published]} -> {:ok, published}
      {0, []} -> {:error, :already_published}
    end
  end

  # A wrong field name here fails at compile time. user_id is the post's
  # author; if anyone else can publish, pass the acting user in instead.
  defp publish_log(%Post{} = post) do
    %Log{
      action: "post.published",
      resource_type: "post",
      resource_id: post.id,
      user_id: post.user_id
    }
  end
end

