# Assumptions and decisions:
#
# - The posts table already exists with title, body, user_id and timestamps,
#   and has integer ids. Only published_at is new.
# - The User schema is not changed, so nothing here needs `has_many :posts`.
# - A post with a NULL published_at is a draft. list_user_posts/1 and
#   get_post!/1 return drafts too, because no visibility rule was given. If
#   either page is public, add `where: not is_nil(p.published_at)` to its query.
# - Field names and types on MyApp.Audit.Log are assumed. See publish_log/1.

